-- Day 1: RBAC, Database, Medallion Schemas & Resource Governance
-- =====================================================================
USE ROLE ACCOUNTADMIN;

-- 1. Create Dedicated Service/Admin Role
CREATE ROLE IF NOT EXISTS COMPLIANCE_AI_ADMIN;
GRANT ROLE COMPLIANCE_AI_ADMIN TO USER ABHISHEK;

-- 2. Hardware Resource Monitor (5 Credit FinOps Safety Cap)
CREATE RESOURCE MONITOR IF NOT EXISTS CORTEX_DEV_MONITOR
    WITH CREDIT_QUOTA = 5
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    NOTIFY_USERS = (ABHISHEK)
    TRIGGERS 
        ON 80 PERCENT DO NOTIFY
        ON 100 PERCENT DO SUSPEND;

-- 3. Dedicated Compute Warehouse
CREATE WAREHOUSE IF NOT EXISTS CORTEX_WH
    WITH WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    RESOURCE_MONITOR = CORTEX_DEV_MONITOR;

-- 4. Medallion Database & Schemas
CREATE DATABASE IF NOT EXISTS COMPLIANCE_INTEL_DB;
CREATE SCHEMA IF NOT EXISTS COMPLIANCE_INTEL_DB.RAW_DOCS;
CREATE SCHEMA IF NOT EXISTS COMPLIANCE_INTEL_DB.AUDIT_GOLD;

-- 5. Delegate Ownership & Privileges
GRANT OWNERSHIP ON DATABASE COMPLIANCE_INTEL_DB TO ROLE COMPLIANCE_AI_ADMIN;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE COMPLIANCE_INTEL_DB TO ROLE COMPLIANCE_AI_ADMIN;
GRANT ALL PRIVILEGES ON WAREHOUSE CORTEX_WH TO ROLE COMPLIANCE_AI_ADMIN;
GRANT CREATE STREAMLIT ON SCHEMA COMPLIANCE_INTEL_DB.AUDIT_GOLD TO ROLE COMPLIANCE_AI_ADMIN;